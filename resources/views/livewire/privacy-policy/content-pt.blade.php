    <section id="sharing">
        <h2>5. Com quem partilhamos os dados</h2>
        <p>Não vendemos nem cedemos os seus dados para fins comerciais. Os dados de cada abrigo só são acessíveis à equipa desse abrigo e aos administradores da plataforma. Podem ainda ser tratados por prestadores de serviços que nos ajudam a operar a plataforma (alojamento e envio de e-mails), sempre com garantias contratuais adequadas, ou comunicados às autoridades quando a lei o exija.</p>
    </section>

    <section id="retention">
        <h2>6. Durante quanto tempo guardamos os dados</h2>
        <ul>
            <li><strong>Contas de utilizador:</strong> enquanto a conta estiver ativa;</li>
            <li><strong>Candidaturas de adoção:</strong> apagadas automaticamente 6 meses após a última alteração;</li>
            <li><strong>Adoções e apadrinhamentos:</strong> durante o tempo necessário ao acompanhamento do animal e ao cumprimento das obrigações legais aplicáveis;</li>
            <li><strong>Sócios:</strong> enquanto durar a qualidade de sócio e, depois dela, apenas pelo período exigido por lei (por exemplo, para os registos de quotas);</li>
            <li><strong>Voluntários:</strong> durante a colaboração e, depois dela, apenas pelo período exigido por lei;</li>
            <li><strong>Sessões:</strong> expiram automaticamente após um período de inatividade.</li>
        </ul>
        <p>Os registos eliminados podem ser mantidos durante um período limitado, sem acesso normal, para efeitos de auditoria e recuperação de erros.</p>
    </section>

    <section id="rights">
        <h2>7. Os seus direitos</h2>
        <p>Pode, a qualquer momento, pedir o <strong>acesso</strong>, a <strong>retificação</strong>, o <strong>apagamento</strong>, a <strong>limitação</strong> do tratamento ou a <strong>portabilidade</strong> dos seus dados, <strong>opor-se</strong> ao tratamento baseado em interesse legítimo e <strong>retirar o consentimento</strong> que tenha dado, sem afetar o tratamento feito até essa data.</p>
        <p>Para exercer estes direitos, contacte diretamente o abrigo com quem se relacionou (os contactos estão na página de cada animal)@if ($contactEmail), ou escreva-nos para <a href="mailto:{{ $contactEmail }}">{{ $contactEmail }}</a>@endif. Responderemos no prazo máximo de um mês.</p>
        <p>Tem também o direito de apresentar reclamação à Comissão Nacional de Proteção de Dados (CNPD), em <a href="https://www.cnpd.pt" target="_blank" rel="noopener">www.cnpd.pt</a>.</p>
    </section>

